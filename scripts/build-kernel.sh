#!/usr/bin/env bash
# Reproducible Xiaomi MIX 4 (odin) 5.4 build with pinned BakaSU + SUSFS v2.4.0.
# Build inputs live in a fresh private temp directory; only named artifacts are
# atomically updated in the repository's marker-owned out/ directory.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd -P)"
OUT="$ROOT/out"
OUT_MARKER="$OUT/.kernel-susfs-2.4-generated-output-v1"

KERNEL_URL="https://github.com/Inkypen79/kernel_xiaomi_odin.git"
KERNEL_REF="50e0141b29b62be21632c768e4818348098ac6cd"
MGLRU_PATCH="$ROOT/port/mglru/odin-mglru.patch"
MGLRU_PINS="$ROOT/port/mglru/source-pins.json"
LZ4K_PATCH="$ROOT/port/lz4k/openEuler-pr-1277.patch"
KCOMPRESSD_RFC_URL="https://lore.kernel.org/lkml/20250430082651.3152444-1-qun-wei.lin@mediatek.com/"
BAKASU_REF="55f3dcb11a0ce5b8aad3cb9763b200fe52efe218"
BAKASU_MANAGER_FIX_REF="7b65bde0710b5e7c6f755545cb15a4abd417f3a8"
BAKASU_MANAGER_FIX_PATH="manager/app/src/main/java/org/bakasu/bakasu/ui/webui/WebViewInterface.kt"
BAKASU_URL="https://github.com/Baka-SU/BakaSU.git"
SUSFS_UPSTREAM_URL="https://gitlab.com/simonpunk/susfs4ksu.git"
SUSFS_UPSTREAM_BRANCH="gki-android12-5.10"
SUSFS_UPSTREAM_REF="784ac9e6fd49bb02499b5b60c57ccc9d0c680204"
SUSFS_PORT_BASE_REF="6dff25f2b2508f91df309e537771d612dccd201a"
SUSFS_RELEASE_REF="45a057536ddba12fd59fb583a8f5375f83be703e"
PORT_MANIFEST="$ROOT/port/SHA256SUMS"
AOSP_CLANG_URL="https://android.googlesource.com/platform/prebuilts/clang/host/linux-x86"
AOSP_CLANG_TAG="android-17.0.0_r1"
AOSP_CLANG_REF="29182889399818f97baa65ea238c80e8117981eb"
CLANG_DIR="clang-r596125"
CLANG_VERSION_EXPECT="clang version 22.0.2"
AK3_URL="https://github.com/osm0sis/AnyKernel3.git"
AK3_REF="41f04bdb4ee30a44e429c2c1131d5e8bb32b15f1"
ZIP_NAME="Xiaomi-MIX4-odin-Los24-GApps-A17-k5.4.302-SUSFS2.4-BakaSU-sync-up-55f3dcb-SIDHashFix-DailyPower-LZ4K-Kcompressd-DefaultOn-Q32-MGLRU-EnabledDefault-RCU-NOCBS-ALL-DIAGNOSTIC-UNTESTED.zip"
BASELINE_BUILD_COMMIT="dad714c595340ab4033a52a82bfd54b1d5ef8364"
BASELINE_CONFIG="$ROOT/port/diagnostic/odin-2026-11-19-baseline.config"
BASELINE_CONFIG_SHA256="85e9bc965e4303bb88ac3f393fd6b99d27114bea4596f6e58e5fc00dfa79d065"
BASELINE_ZIP_NAME="Xiaomi-MIX4-odin-Los24-GApps-A17-k5.4.302-SUSFS2.4-BakaSU-sync-up-55f3dcb-SIDHashFix-DailyPower-LZ4K-Kcompressd-DefaultOn-Q32-MGLRU-EnabledDefault-UNTESTED.zip"
BASELINE_ZIP_SHA256="40ae8ffd6664a695afd06b2d222b91d985426ce6d9ae3c1f36ae57471eea71ac"
JOBS="${JOBS:-$(nproc)}"
IDLE_GOVERNOR="${IDLE_GOVERNOR:-teo}"

step() { printf '\n===== %s =====\n' "$*"; }
fail() { echo "ERROR: $*" >&2; exit 1; }
case "$IDLE_GOVERNOR" in
  teo) ;;
  *) fail "the RCU-only diagnostic must keep the Nov 19 TEO baseline (IDLE_GOVERNOR=teo)" ;;
esac
sh -n "$ROOT/scripts/odin-schedutil-fast-down.sh" || fail "runtime profile has shell syntax errors"
bash -n "$ROOT/scripts/test-odin-schedutil-fast-down.sh" || fail "runtime profile test has shell syntax errors"
python3 "$ROOT/scripts/test-odin-schedutil-default.py" || fail "schedutil default patch regression failed"
python3 "$ROOT/scripts/test-odin-mglru.py" --target-commit "$KERNEL_REF" || fail "MGLRU patch pin or compatibility metadata check failed"
python3 "$ROOT/scripts/test_lz4k.py" || fail "LZ4K codec or 5.4 adapter regression failed"
python3 -m py_compile "$ROOT/scripts/apply-kcompressd.py" "$ROOT/scripts/test-kcompressd-5.4.py" || fail "Kcompressd Python tooling has syntax errors"
[[ -s "$ROOT/port/kcompressd/mm/kcompressd.c" ]] || fail "missing Kcompressd worker source"

# Refuse to follow a redirected output path or overwrite an unowned directory.
[[ ! -L "$OUT" ]] || fail "out/ must not be a symbolic link"
if [[ -e "$OUT" ]]; then
  [[ -d "$OUT" ]] || fail "out/ exists but is not a directory"
  [[ "$(realpath -m "$OUT")" == "$ROOT/out" ]] || fail "out/ resolves outside this repository"
  [[ ! -L "$OUT_MARKER" && -f "$OUT_MARKER" ]] || fail "existing out/ is not marked as generated by this build script"
  [[ "$(cat "$OUT_MARKER")" == "kernel-susfs-2.4 generated output v1" ]] || fail "out/ marker has unexpected content"
else
  mkdir -- "$OUT"
  printf '%s\n' 'kernel-susfs-2.4 generated output v1' > "$OUT_MARKER"
fi

TMP_BASE="$(cd "${TMPDIR:-/tmp}" && pwd -P)"
BUILD_TMP="$(mktemp -d "$TMP_BASE/kernel-susfs-2.4-build.XXXXXXXX")"
case "$BUILD_TMP" in
  "$TMP_BASE"/kernel-susfs-2.4-build.*) ;;
  *) fail "temporary build directory is outside the expected private namespace" ;;
esac
cleanup() {
  local rc=$?
  trap - EXIT
  if [[ -n "${BUILD_TMP:-}" && -d "$BUILD_TMP" && ! -L "$BUILD_TMP" ]]; then
    case "$BUILD_TMP" in
      "$TMP_BASE"/kernel-susfs-2.4-build.*) rm -rf -- "$BUILD_TMP" ;;
      *) echo "Refusing to clean unexpected temporary path: $BUILD_TMP" >&2 ;;
    esac
  fi
  exit "$rc"
}
trap cleanup EXIT

WORK="$BUILD_TMP/work"
OUT_STAGE="$BUILD_TMP/out"
KSRC="$WORK/kernel"
KOUT="$WORK/kout"
TOOLBIN="$WORK/toolchain/bin"
mkdir -p "$WORK" "$OUT_STAGE" "$TOOLBIN"

[[ -d "$ROOT/port/out" ]] || fail "run this script from the repository checkout"
[[ -f "$ROOT/port/out/security/selinux/ss/services.c" ]] || fail "missing completed services.c port"
[[ -f "$ROOT/port/out/security/selinux/selinuxfs.c" ]] || fail "missing completed selinuxfs.c port"
[[ -f "$PORT_MANIFEST" && ! -L "$PORT_MANIFEST" ]] || fail "missing regular port source manifest"

step "verify exact local SUSFS port file set and SHA-256 manifest"
python3 - "$ROOT" "$PORT_MANIFEST" <<'PYEOF'
from pathlib import Path
import subprocess
import sys

root = Path(sys.argv[1])
manifest = Path(sys.argv[2])
port_root = root / "port/out"
entries = list(port_root.rglob("*"))
symlinks = [p.relative_to(root).as_posix() for p in entries if p.is_symlink()]
special = [p.relative_to(root).as_posix() for p in entries if not p.is_symlink() and not (p.is_file() or p.is_dir())]
if symlinks or special:
    raise SystemExit(f"unsupported port tree entries; symlinks={symlinks}, special={special}")
expected = []
for number, line in enumerate(manifest.read_text().splitlines(), 1):
    parts = line.split("  ", 1)
    if len(parts) != 2 or len(parts[0]) != 64:
        raise SystemExit(f"invalid port manifest line {number}")
    expected.append(parts[1])
actual = sorted(p.relative_to(root).as_posix() for p in entries if p.is_file())
if sorted(expected) != actual:
    missing = sorted(set(expected) - set(actual))
    extra = sorted(set(actual) - set(expected))
    raise SystemExit(f"port manifest file-set mismatch; missing={missing}, extra={extra}")
subprocess.run(["sha256sum", "-c", "port/SHA256SUMS"], cwd=root, check=True)
print("local port tree file set and checksums: PASS")
PYEOF
PORT_MANIFEST_SHA256="$(sha256sum "$PORT_MANIFEST" | awk '{print $1}')"
LZ4K_PATCH_SHA256="$(sha256sum "$LZ4K_PATCH" | awk '{print $1}')"
KCOMPRESSD_ADAPTER_SHA256="$(sha256sum "$ROOT/scripts/apply-kcompressd.py" | awk '{print $1}')"
KCOMPRESSD_WORKER_SHA256="$(sha256sum "$ROOT/port/kcompressd/mm/kcompressd.c" | awk '{print $1}')"
KCOMPRESSD_TEST_SHA256="$(sha256sum "$ROOT/scripts/test-kcompressd-5.4.py" | awk '{print $1}')"

if [[ "${INSTALL_DEPS:-1}" == 1 ]]; then
  step "install host build dependencies"
  sudo apt-get update -qq
  sudo apt-get install -y -qq --no-install-recommends \
    bc bison flex libssl-dev libelf-dev libdw-dev dwarves \
    cpio zip unzip rsync python3 git curl wget xz-utils zstd patch \
    build-essential gcc-aarch64-linux-gnu
fi

step "fetch pinned Inkypen 5.4 baseline"
git init -q "$KSRC"
git -C "$KSRC" remote add origin "$KERNEL_URL"
git -C "$KSRC" fetch --depth=1 origin "$KERNEL_REF"
git -C "$KSRC" checkout --detach -q FETCH_HEAD
[[ "$(git -C "$KSRC" rev-parse HEAD)" == "$KERNEL_REF" ]] || fail "kernel checkout is not the pinned $KERNEL_REF"
step "apply MIX 4 daily-power schedutil default to the pinned source"
SCHEDUTIL_SOURCE="$KSRC/kernel/sched/cpufreq_schedutil.c"
python3 "$ROOT/scripts/apply-odin-schedutil-default.py" "$SCHEDUTIL_SOURCE"
grep -Fqx $'\t/* odin-daily-power: preserve ramp-up delay; allow immediate ramp-down */' "$SCHEDUTIL_SOURCE" || fail "daily-power source marker is missing"
grep -Fqx $'\ttunables->up_rate_limit_us = cpufreq_policy_transition_delay_us(policy);' "$SCHEDUTIL_SOURCE" || fail "original ramp-up initialization was not preserved"
grep -Fqx $'\ttunables->down_rate_limit_us = 0;' "$SCHEDUTIL_SOURCE" || fail "down-rate default was not set to zero"
SCHEDUTIL_DEFAULT_PATCH_SHA256="$(sha256sum "$ROOT/scripts/apply-odin-schedutil-default.py" | awk '{print $1}')"
step "apply optional LZ4K zram compressor with 5.4 compatibility adapters"
python3 "$ROOT/scripts/apply_lz4k_patch.py" "$KSRC" || fail "LZ4K source integration failed"
SOURCE_DATE_EPOCH="$(git -C "$KSRC" show -s --format=%ct HEAD)"
[[ "$SOURCE_DATE_EPOCH" =~ ^[0-9]+$ ]] || fail "could not derive SOURCE_DATE_EPOCH from the pinned kernel commit"
export SOURCE_DATE_EPOCH
export TZ=UTC LC_ALL=C
export KBUILD_BUILD_TIMESTAMP="$(date -d "@$SOURCE_DATE_EPOCH" '+%a %b %d %H:%M:%S UTC %Y')"
export KBUILD_BUILD_USER="kernel-builder"
export KBUILD_BUILD_HOST="kernel-susfs-2.4"
export KBUILD_BUILD_VERSION="1"
: > "$KSRC/.scmversion"

step "verify AOSP Clang release tag and fetch the exact commit tree"
CLANG_TAG_REFS="$(git -c http.version=HTTP/1.1 ls-remote "$AOSP_CLANG_URL" \
  "refs/tags/$AOSP_CLANG_TAG" "refs/tags/$AOSP_CLANG_TAG^{}")" || fail "could not resolve AOSP Clang tag"
CLANG_ACTUAL_REF="$(awk -v tag="refs/tags/$AOSP_CLANG_TAG^{}" '$2 == tag { print $1 }' <<< "$CLANG_TAG_REFS")"
if [[ -z "$CLANG_ACTUAL_REF" ]]; then
  CLANG_ACTUAL_REF="$(awk -v tag="refs/tags/$AOSP_CLANG_TAG" '$2 == tag { print $1 }' <<< "$CLANG_TAG_REFS")"
fi
[[ "$CLANG_ACTUAL_REF" == "$AOSP_CLANG_REF" ]] || fail "AOSP Clang tag resolved to ${CLANG_ACTUAL_REF:-<missing>}, expected $AOSP_CLANG_REF"
CLANG_HOME="$WORK/$CLANG_DIR"
mkdir -p "$CLANG_HOME"
CLANG_CACHE_ARGS=()
if [[ -n "${CLANG_ARCHIVE_CACHE:-}" ]]; then
  CLANG_CACHE_ARGS=(--cache-dir "$CLANG_ARCHIVE_CACHE")
fi
python3 "$ROOT/scripts/fetch-aosp-clang.py" \
  "$AOSP_CLANG_URL" "$CLANG_ACTUAL_REF" "$CLANG_DIR" "$CLANG_HOME" \
  "${CLANG_CACHE_ARGS[@]}" || fail "could not fetch and verify the pinned AOSP Clang tree"
[[ -x "$CLANG_HOME/bin/clang" ]] || fail "pinned AOSP Clang executable is missing"
for tool in "$CLANG_HOME/bin/"*; do
  [[ -x "$tool" ]] && ln -s "$tool" "$TOOLBIN/$(basename "$tool")"
done
export PATH="$TOOLBIN:$PATH"
CLANG_VERSION="$(clang --version | head -n 1)"
grep -Fq "$CLANG_VERSION_EXPECT" <<< "$CLANG_VERSION" || fail "unexpected compiler version: $CLANG_VERSION"
grep -Fq 'based on r596125' <<< "$CLANG_VERSION" || fail "unexpected AOSP clang revision: $CLANG_VERSION"
printf '%s\n' "$CLANG_VERSION"

MAKE_ARGS=(
  -C "$KSRC" O="$KOUT" ARCH=arm64
  CC=clang HOSTCC=clang HOSTCXX=clang++
  KCFLAGS="-ffile-prefix-map=$KSRC=kernel-src -ffile-prefix-map=$KOUT=kernel-out"
  KAFLAGS="-ffile-prefix-map=$KSRC=kernel-src -ffile-prefix-map=$KOUT=kernel-out"
  CLANG_TRIPLE=aarch64-linux-gnu-
  CROSS_COMPILE=aarch64-linux-gnu-
  LD=ld.lld AR=llvm-ar NM=llvm-nm
  OBJCOPY=llvm-objcopy OBJDUMP=llvm-objdump STRIP=llvm-strip
)

step "integrate pinned BakaSU"
curl -fsSL "https://raw.githubusercontent.com/Baka-SU/BakaSU/$BAKASU_REF/kernel/setup.sh" \
  -o "$WORK/bakasu-setup.sh"
(cd "$KSRC" && bash "$WORK/bakasu-setup.sh" "$BAKASU_REF")
[[ -d "$KSRC/KernelSU/.git" ]] || fail "BakaSU setup did not create KernelSU git checkout"
git -C "$KSRC/KernelSU" checkout --detach -q "$BAKASU_REF"
[[ "$(git -C "$KSRC/KernelSU" rev-parse HEAD)" == "$BAKASU_REF" ]] || fail "BakaSU checkout is not pinned"

step "apply pinned BakaSU Manager WebView fix (#35262) without changing sync-up kernel code"
git -C "$KSRC/KernelSU" fetch --no-tags origin "$BAKASU_MANAGER_FIX_REF" || fail "could not fetch pinned BakaSU Manager fix"
[[ "$(git -C "$KSRC/KernelSU" rev-parse "$BAKASU_MANAGER_FIX_REF^{commit}")" == "$BAKASU_MANAGER_FIX_REF" ]] || fail "BakaSU Manager fix commit is unavailable"
git -C "$KSRC/KernelSU" cherry-pick --no-commit "$BAKASU_MANAGER_FIX_REF" || fail "BakaSU Manager fix does not apply cleanly to pinned sync-up"
[[ "$(git -C "$KSRC/KernelSU" diff --cached --name-only)" == "$BAKASU_MANAGER_FIX_PATH" ]] || fail "BakaSU Manager fix touched unexpected paths"
git -C "$KSRC/KernelSU" diff --cached --check || fail "BakaSU Manager fix has whitespace errors"
grep -Fq 'private fun postToWebView(action: (android.webkit.WebView) -> Unit)' "$KSRC/KernelSU/$BAKASU_MANAGER_FIX_PATH" || fail "BakaSU Manager WebView fix marker is missing"
grep -Fq 'mainHandler.post { state.webView?.let(action) }' "$KSRC/KernelSU/$BAKASU_MANAGER_FIX_PATH" || fail "BakaSU Manager null-safe main-thread dispatch is missing"
git -C "$KSRC/KernelSU" reset -q --mixed "$BAKASU_REF"
[[ "$(git -C "$KSRC/KernelSU" diff --name-only)" == "$BAKASU_MANAGER_FIX_PATH" ]] || fail "BakaSU integration contains unexpected working-tree changes"
BAKASU_MANAGER_PATCH_SHA256="$(git -C "$KSRC/KernelSU" diff --binary "$BAKASU_REF" -- "$BAKASU_MANAGER_FIX_PATH" | sha256sum | awk '{print $1}')"
RUNTIME_PROFILE_SHA256="$(sha256sum "$ROOT/scripts/odin-schedutil-fast-down.sh" | awk '{print $1}')"

step "overlay verified SUSFS v2.4.0 port (upstream reference $SUSFS_UPSTREAM_REF)"
cp -a "$ROOT/port/out/." "$KSRC/"
grep -q 'SUSFS_VERSION "v2.4.0"' "$KSRC/include/linux/susfs.h" || fail "overlay is not SUSFS v2.4.0"
for required in \
  fs/susfs.c security/selinux/selinuxfs.c security/selinux/ss/services.c \
  security/selinux/ss/susfs.h \
  fs/exec.c fs/namei.c fs/namespace.c kernel/sys.c block/ioprio.c; do
  [[ -s "$KSRC/$required" ]] || fail "missing overlay file $required"
done
for required in \
  susfs_selinux_inode_setxattr susfs_selinux_inode_post_setxattr \
  handle_selinux_inode_setxattr handle_selinux_inode_post_setxattr; do
  grep -q "$required" "$KSRC/security/selinux/hooks.c" || fail "missing latest SUSFS SELinux hook: $required"
done
grep -q 'susfs_security_context_to_sid_default' "$KSRC/security/selinux/ss/services.c" || fail "missing SUSFS default SID wrapper"
grep -q 'susfs_security_context_to_sid_force' "$KSRC/security/selinux/ss/services.c" || fail "missing SUSFS force SID wrapper"
grep -q 'LSM_HOOK_INIT(inode_setxattr, handle_selinux_inode_setxattr)' "$KSRC/security/selinux/hooks.c" || fail "latest SUSFS inode_setxattr hook is not registered"
grep -q 'LSM_HOOK_INIT(inode_post_setxattr, handle_selinux_inode_post_setxattr)' "$KSRC/security/selinux/hooks.c" || fail "latest SUSFS inode_post_setxattr hook is not registered"

step "apply odin-specific MGLRU 5.4 backport (enabled by default; runtime kill switch retained)"
git -C "$KSRC" apply --check --whitespace=error --recount "$MGLRU_PATCH" || fail "MGLRU patch does not apply cleanly after SUSFS overlay"
git -C "$KSRC" apply --whitespace=error --recount "$MGLRU_PATCH" || fail "could not apply pinned MGLRU patch"
MGLRU_PATCH_SHA256="$(sha256sum "$MGLRU_PATCH" | awk '{print $1}')"
python3 "$ROOT/scripts/test-odin-mglru.py" --target-commit "$KERNEL_REF" --source "$KSRC" || \
  fail "MGLRU source integration regression failed"

step "apply pinned odin Linux 5.4.302 Kcompressd backport and run static regressions"
python3 "$ROOT/scripts/apply-kcompressd.py" "$KSRC" "$ROOT/port/kcompressd/mm/kcompressd.c" || \
  fail "Kcompressd 5.4 source adapter refused or failed"
python3 "$ROOT/scripts/test-kcompressd-5.4.py" "$KSRC" || \
  fail "Kcompressd 5.4 static regression checks failed"
python3 "$ROOT/scripts/test-odin-mglru.py" --target-commit "$KERNEL_REF" --source "$KSRC" || \
  fail "MGLRU checks failed after Kcompressd integration"

step "add 5.4 BakaSU compatibility export"
python3 - "$KSRC/fs/namespace.c" <<'PYEOF'
import sys
from pathlib import Path

path = Path(sys.argv[1])
source = path.read_text()
if "EXPORT_SYMBOL(do_mount);" in source:
    print("fs/namespace.c: do_mount export already present")
    raise SystemExit(0)
anchor = "long do_mount(const char *dev_name, const char __user *dir_name,"
if source.count(anchor) != 1:
    raise SystemExit("ERROR: expected exactly one 5.4 do_mount definition")
start = source.index(anchor)
end = source.find("\n}\n", start)
if end < 0:
    raise SystemExit("ERROR: could not find end of do_mount definition")
end += len("\n}\n")
source = source[:end] + "EXPORT_SYMBOL(do_mount);\n" + source[end:]
path.write_text(source)
print("exported do_mount for BakaSU's pre-5.9 mount compatibility path")
PYEOF

step "enable the two SUSFS v2.4 Kconfig features"
python3 "$ROOT/scripts/add-bakasu-susfs-kconfig.py" "$KSRC/KernelSU/kernel/Kconfig"

step "audit BakaSU/SUSFS wiring"
[[ -L "$KSRC/drivers/kernelsu" ]] || fail "drivers/kernelsu is not the BakaSU symlink"
[[ "$(readlink -f "$KSRC/drivers/kernelsu/Kconfig")" == "$(readlink -f "$KSRC/KernelSU/kernel/Kconfig")" ]] || fail "BakaSU Kconfig symlink does not resolve to pinned source"
SUSFS_COMPAT_MK="$KSRC/KernelSU/kernel/tools/susfs_compat.mk"
[[ -s "$SUSFS_COMPAT_MK" ]] || fail "pinned BakaSU SUSFS compatibility makefile is missing"
grep -q 'KSU_COMPAT_HAS_SUSFS_FEATURE_SELINUX_HIDE' "$SUSFS_COMPAT_MK" || fail "pinned BakaSU lacks SUSFS SELinux-hide compatibility macro"
grep -Fq 'include $(KSU_SRC)/tools/susfs_compat.mk' "$KSRC/KernelSU/kernel/Kbuild" || fail "pinned BakaSU does not load SUSFS compatibility makefile"
for symbol in KSU_SUSFS_AVD KSU_SUSFS_PRIORITY_UID_FILTER; do
  [[ "$(grep -c "^config $symbol$" "$KSRC/KernelSU/kernel/Kconfig")" == 1 ]] || fail "$symbol Kconfig declaration missing or duplicated"
done
if grep -q 'bakasu-wired' "$KSRC/KernelSU/kernel/compat/kernel_compat.c" "$KSRC/include/linux/susfs_def.h"; then
  fail "v2.1-only compatibility glue was copied into the v2.4 build"
fi
for hook in \
  ksu_handle_setresuid ksu_handle_execveat ksu_handle_faccessat \
  ksu_handle_stat ksu_handle_vfs_fstat ksu_handle_sys_read \
  ksu_handle_sys_reboot ksu_handle_input_handle_event; do
  grep -Rqs "$hook" "$KSRC/fs" "$KSRC/kernel" "$KSRC/drivers/input" || fail "missing BakaSU inline hook call site: $hook"
done

step "run SELinux context-to-SID hash regression checks"
python3 "$ROOT/scripts/test-susfs-selinux-context-hash.py" "$KSRC" || \
  fail "SUSFS/BakaSU SELinux context-to-SID regression checks failed"

step "configure odin_defconfig"
make "${MAKE_ARGS[@]}" odin_defconfig
CFG="$KOUT/.config"
ZRAM_KCONFIG_BEFORE="$(grep -E '^(CONFIG_ZRAM[^=]*=|# CONFIG_ZRAM)' "$CFG" || true)"
# Use scheduler-driven CPU frequency scaling and a testable TEO idle policy.
# Keep performance/menu compiled, preserve Qualcomm LPM, and let the bootloader
# append its arguments rather than forcing a replacement kernel command line.
"$KSRC/scripts/config" --file "$CFG" \
  --enable KSU --enable KPROBES --enable KALLSYMS_ALL \
  --enable EXT4_FS --enable HEADERS_INSTALL \
  --enable KSU_SUSFS --enable KSU_SUSFS_AVD \
  --enable KSU_SUSFS_PRIORITY_UID_FILTER \
  --enable CRYPTO_LZ4K \
  --enable LRU_GEN --enable LRU_GEN_ENABLED --disable LRU_GEN_STATS \
  --enable KCOMPRESSD \
  --enable CPU_FREQ_GOV_SCHEDUTIL \
  --enable CPU_FREQ_DEFAULT_GOV_SCHEDUTIL \
  --enable CPU_FREQ_GOV_PERFORMANCE \
  --enable CPU_IDLE_GOV_MENU --enable CPU_IDLE_GOV_TEO \
  --set-str CMDLINE "cgroup_disable=pressure cpuidle.governor=$IDLE_GOVERNOR rcu_nocbs=all"
make "${MAKE_ARGS[@]}" olddefconfig
ZRAM_KCONFIG_AFTER="$(grep -E '^(CONFIG_ZRAM[^=]*=|# CONFIG_ZRAM)' "$CFG" || true)"
[[ "$ZRAM_KCONFIG_BEFORE" == "$ZRAM_KCONFIG_AFTER" ]] || \
  fail "LZ4K integration changed existing zram configuration/default"
python3 "$ROOT/scripts/test-odin-mglru.py" --target-commit "$KERNEL_REF" --source "$KSRC" --config "$CFG" || \
  fail "MGLRU configuration or thermal protection regression failed"
python3 "$ROOT/scripts/test-kcompressd-5.4.py" "$KSRC" || \
  fail "Kcompressd default/runtime regression failed after configuration"
grep -q '^CONFIG_KCOMPRESSD=y$' "$CFG" || fail "CONFIG_KCOMPRESSD was dropped by olddefconfig"
for config in \
  CONFIG_KSU CONFIG_KSU_SUSFS CONFIG_KSU_SUSFS_AVD \
  CONFIG_KSU_SUSFS_PRIORITY_UID_FILTER CONFIG_CRYPTO_LZ4K \
  CONFIG_LZ4K_COMPRESS CONFIG_LZ4K_DECOMPRESS CONFIG_CPU_FREQ_GOV_SCHEDUTIL \
  CONFIG_CPU_FREQ_DEFAULT_GOV_SCHEDUTIL CONFIG_CPU_FREQ_GOV_PERFORMANCE \
  CONFIG_CPU_IDLE_GOV_MENU CONFIG_CPU_IDLE_GOV_TEO CONFIG_ARM_QCOM_LPM_CPUIDLE \
  CONFIG_NO_HZ_IDLE CONFIG_RCU_FAST_NO_HZ CONFIG_RCU_NOCB_CPU \
  CONFIG_SCHED_WALT CONFIG_UCLAMP_TASK CONFIG_UCLAMP_TASK_GROUP \
  CONFIG_THERMAL CONFIG_CPU_THERMAL CONFIG_THERMAL_GOV_STEP_WISE \
